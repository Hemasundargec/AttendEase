import ExcelJS from 'exceljs'
import { MONTHS } from './sheet.js'

const FONT = 'Arial'
const fill = (argb) => ({ type: 'pattern', pattern: 'solid', fgColor: { argb } })
const COLORS = { P: 'FF1E5B2F', Pt: 'FF7A4B00', A: 'FF8C1D2F', H: 'FF3E2B1D' }

// Builds the downloadable workbook: the sheet shown in the app, plus a subject-wise tab.
export async function buildWorkbook({ user, sheet, subjectRows }) {
  const wb = new ExcelJS.Workbook()
  wb.creator = 'AttendEase'
  wb.created = new Date()

  const ws = wb.addWorksheet(`Attendance ${sheet.year}`, { views: [{ state: 'frozen', xSplit: 1, ySplit: 9 }] })
  ws.columns = [{ width: 12 }, ...MONTHS.map(() => ({ width: 11 }))]
  const bold = { name: FONT, bold: true }
  ws.mergeCells('A1:M1'); ws.getCell('A1').value = `Attendance sheet ${sheet.year}`; ws.getCell('A1').font = { name: FONT, bold: true, size: 16, color: { argb: 'FF3E2B1D' } }
  ws.getCell('A2').value = 'Name'; ws.getCell('B2').value = user.name
  ws.getCell('A3').value = 'Roll number'; ws.getCell('B3').value = user.rollNumber
  ws.getCell('A4').value = 'Branch'; ws.getCell('B4').value = `${user.branch}, year ${user.year}, semester ${user.semester}`
  for (const r of [2, 3, 4]) { ws.getCell(`A${r}`).font = bold; ws.getCell(`B${r}`).font = { name: FONT } }

  // Totals are formulas over the grid, so they stay correct if a cell is edited.
  const first = 10, last = 40
  const rng = `$B$${first}:$M$${last}`
  const t = sheet.totals
  const tiles = [['Total present', 'P'], ['Total partial', 'Pt'], ['Total absent', 'A'], ['Total holiday / no class', 'H']]
  tiles.forEach(([label, code], i) => {
    const col = 2 + i * 3 // B, E, H, K
    ws.mergeCells(5, col, 5, col + 1); ws.mergeCells(6, col, 6, col + 1)
    const l = ws.getCell(5, col), v = ws.getCell(6, col)
    l.value = label; l.font = bold; l.fill = fill('FFE5E4E2')
    v.value = { formula: `COUNTIF(${rng},"${code}")`, result: { P: t.present, Pt: t.partial, A: t.absent, H: t.holiday }[code] }
    v.font = { name: FONT, bold: true, size: 14, color: { argb: COLORS[code] } }; v.fill = fill('FFE5E4E2')
    v.alignment = { horizontal: 'left' }
  })
  ws.getCell('A7').value = 'P = attended all classes   Pt = attended some   A = absent (no class attended)   H = holiday / no classes (Sundays included)   blank = not entered'
  ws.getCell('A7').font = { name: FONT, italic: true, size: 10 }

  const head = ws.getRow(9)
  head.values = ['Date | Month', ...MONTHS]
  head.eachCell((c) => { c.font = { ...bold, color: { argb: 'FFFFFFFF' } }; c.fill = fill('FF6F4E37'); c.alignment = { horizontal: 'center' } })
  sheet.rows.forEach((row, i) => {
    const r = ws.getRow(first + i)
    r.getCell(1).value = i + 1; r.getCell(1).font = bold; r.getCell(1).alignment = { horizontal: 'center' }
    row.forEach((mark, m) => {
      const c = r.getCell(m + 2)
      c.alignment = { horizontal: 'center' }
      if (mark === null) { c.value = '-'; c.font = { name: FONT, color: { argb: 'FF9A9A9A' } }; c.fill = fill('FFF2F2F2'); return }
      c.value = mark || null
      c.font = { name: FONT, bold: Boolean(mark), color: { argb: COLORS[mark] || 'FF000000' } }
      if (mark === 'P') c.fill = fill('FFE3F1E6'); else if (mark === 'A') c.fill = fill('FFF8E1E4'); else if (mark === 'Pt') c.fill = fill('FFFFF0D6'); else if (mark === 'H') c.fill = fill('FFE6E0F0')
    })
  })
  ws.getCell(`A${last + 2}`).value = `Classes attended: ${t.classesAttended} of ${t.classesConducted} conducted in ${sheet.year}`
  ws.getCell(`A${last + 2}`).font = bold
  ws.getCell(`A${last + 3}`).value = 'Each day is worked out from the classes you entered that day. Generated by AttendEase.'
  ws.getCell(`A${last + 3}`).font = { name: FONT, italic: true, size: 10 }
  ws.pageSetup = { orientation: 'landscape', fitToPage: true, fitToWidth: 1, fitToHeight: 1 }

  const sw = wb.addWorksheet('Subject-wise')
  sw.columns = [{ width: 12 }, { width: 34 }, { width: 14 }, { width: 14 }, { width: 14 }]
  const h = sw.getRow(1); h.values = ['Code', 'Subject', 'Conducted', 'Attended', 'Percentage']
  h.eachCell((c) => { c.font = { ...bold, color: { argb: 'FFFFFFFF' } }; c.fill = fill('FF6F4E37') })
  subjectRows.forEach((s, i) => {
    const r = i + 2
    sw.getRow(r).values = [s.code, s.name, s.conducted, s.attended, { formula: `IF(C${r}=0,"",ROUND(D${r}*100/C${r},2))`, result: s.conducted ? Math.round((s.attended * 10000) / s.conducted) / 100 : '' }]
    sw.getRow(r).eachCell((c) => { c.font = { name: FONT } })
  })
  const n = subjectRows.length + 2
  sw.getRow(n).values = ['Total', '', { formula: `SUM(C2:C${n - 1})` }, { formula: `SUM(D2:D${n - 1})` }, { formula: `IF(C${n}=0,"",ROUND(D${n}*100/C${n},2))` }]
  sw.getRow(n).eachCell((c) => { c.font = bold })
  sw.getCell(`A${n + 2}`).value = `Subjects and counts for ${sheet.year}.`; sw.getCell(`A${n + 2}`).font = { name: FONT, italic: true, size: 10 }
  return wb
}
